import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('./tips.js',import.meta.url),'utf8');
const {tipLines,HoverTip,tipPlacement}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const lines=tipLines('commit',{hash:'1234567890',author:'王小明',date:'2026-11-10T12:00',refs:[{name:'main',kind:'local'},{name:'origin/HEAD',kind:'remote'}],message:'完整訊息\n第二行'});
assert.match(lines[0].text,/12345678.*王小明.*2026-11-10 12:00/);
assert.equal(lines[0].bold,true); assert.equal(lines[1].text,'main'); assert.equal(lines[2].text,'完整訊息\n第二行');
assert.deepEqual(tipLines('badge',[{tooltip:'main\norigin/main\n與遠端同步',kind:'local'}]).map(x=>x.text),['main','origin/main','與遠端同步']);
assert.equal(tipLines('file',{status:'R',oldPath:'舊 名',path:'新 名'})[0].text,'重新命名：舊 名 → 新 名');
assert.equal(tipLines('refresh')[0].text,'重新整理提交歷史');
const hover=new HoverTip(); const first=hover.enter('row',lines); const second=hover.enter('badge',[]);
assert.equal(hover.reveal(first),false); hover.clear('row'); assert.equal(hover.reveal(second),true);
assert.equal(hover.clear(),true); assert.equal(hover.reveal(second),false);
assert.deepEqual(tipPlacement(400,60,88,100),{top:94,maxHeight:300});
assert.deepEqual(tipPlacement(400,350,378,100),{top:244,maxHeight:338});
console.log('通過：提交／徽章／檔案／重新整理內容、延遲 token、離開與捲動取消、上下定位。');
